"""Generate ``web/src/protocol/commands.ts`` from the Python protocol spec.

Usage: ``python scripts/gen_protocol_ts.py`` (run after changing ``piglet.server.protocol``).
"""

from __future__ import annotations

import types
import typing
from pathlib import Path
from typing import Any, Literal

from piglet.server.protocol import COMMANDS, Images

OUTPUT = Path(__file__).resolve().parent.parent / "web" / "src" / "protocol" / "commands.ts"


def ts_type(annotation: Any) -> str:  # noqa: ANN401 - a type translator
    """Translate a Python annotation used in the protocol spec to TypeScript."""
    if annotation is Any:
        return "unknown"
    if annotation is str:
        return "string"
    if annotation in {int, float}:
        return "number"
    if annotation is bool:
        return "boolean"
    if annotation == Images:
        return "ImageContent[]"
    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if origin is Literal:
        return " | ".join(f'"{a}"' for a in args)
    if origin in {typing.Union, types.UnionType}:
        return " | ".join("null" if a is type(None) else ts_type(a) for a in args)
    if origin is list:
        return f"{ts_type(args[0])}[]"
    if origin is dict:
        return "Record<string, unknown>"
    raise TypeError(f"Unsupported annotation {annotation!r}")


def render() -> str:
    """Return the TypeScript module text."""
    lines = [
        "// Generated by scripts/gen_protocol_ts.py from piglet.server.protocol. Do not edit.",
        "",
        "export interface ImageContent {",
        '  type: "image";',
        "  data: string;",
        "  mimeType: string;",
        "}",
        "",
        "export interface CommandMap {",
    ]
    session_commands = []
    for name, (needs_session, fields) in COMMANDS.items():
        members = ["sessionId: string"] if needs_session else []
        if needs_session:
            session_commands.append(name)
        for field, (annotation, default) in fields.items():
            optional = "" if default is ... else "?"
            members.append(f"{field}{optional}: {ts_type(annotation)}")
        body = "; ".join(members)
        lines.append(f"  {name}: {{ {body} }};" if body else f"  {name}: Record<string, never>;")
    lines += [
        "}",
        "",
        "export type CommandType = keyof CommandMap;",
        "",
        "export const SESSION_COMMANDS: ReadonlySet<CommandType> = new Set<CommandType>([",
        *(f'  "{name}",' for name in session_commands),
        "]);",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    """Write the generated file."""
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
