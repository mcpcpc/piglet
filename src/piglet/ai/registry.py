_DATED_SUFFIX = re.compile(r"-\d{8}$")
_PROVIDER_LEVEL_KEYS = ("baseUrl", "api", "headers", "compat")


@functools.cache
def load_catalog() -> tuple[Model, ...]:
    """Return the bundled built-in catalog (generated by ``scripts/sync_catalog.py``)."""
    text = resources.files("piglet.ai").joinpath("catalog.json").read_text(encoding="utf-8")
    return tuple(json.loads(text)["models"])


@dataclass
class ProviderConfig:
    """Provider-level settings from ``models.json`` that are not stored on each model."""

    api_key: str | None = None
    auth_header: bool = False
    name: str | None = None
    oauth: str | None = None


@dataclass
class ResolvedModels:
    """The effective model list after applying ``models.json``."""

    models: list[Model]
    providers: dict[str, ProviderConfig] = field(default_factory=dict)
    errors: list[str] = field(default_factory=list)


def apply_models_config(catalog: Iterable[Model], config: Any) -> ResolvedModels:  # noqa: ANN401
    """Apply a ``models.json`` document to the built-in catalog.

    * A built-in provider id modifies that provider (for example only ``baseUrl`` to proxy it).
    * A new provider id needs ``baseUrl`` and ``api``.
    * A ``models`` entry with an existing id replaces that model; ``modelOverrides`` merges fields.

    Args:
        catalog: Built-in models.
        config: Parsed ``models.json`` (``None`` when absent).

    Returns:
        The effective models, provider configs and any validation errors.
    """
    models = [copy.deepcopy(m) for m in catalog]
    result = ResolvedModels(models=models)
    providers = config.get("providers") if isinstance(config, dict) else None
    if not isinstance(providers, dict):
        return result
    for provider_id, spec in providers.items():
        if not isinstance(spec, dict):
            result.errors.append(f"models.json: provider {provider_id!r} must be an object")
            continue
        _apply_provider(result, provider_id, spec)
    return result


def _apply_provider(result: ResolvedModels, provider_id: str, spec: dict[str, Any]) -> None:
    result.providers[provider_id] = ProviderConfig(
        api_key=spec.get("apiKey"),
        auth_header=bool(spec.get("authHeader")),
        name=spec.get("name"),
        oauth=spec.get("oauth"),
    )
    existing = [m for m in result.models if m["provider"] == provider_id]
    provider_fields = {k: spec[k] for k in _PROVIDER_LEVEL_KEYS if k in spec}
    missing_endpoint = not ({"baseUrl", "api"} <= provider_fields.keys())
    if not existing and missing_endpoint and spec.get("models"):
        result.errors.append(f"models.json: new provider {provider_id!r} needs baseUrl and api")
        return
    for model in existing:
        _merge_fields(model, provider_fields)
    for entry in spec.get("models") or []:
        if not isinstance(entry, dict) or not isinstance(entry.get("id"), str):
            result.errors.append(f"models.json: provider {provider_id!r} has a model without id")
            continue
        _upsert_model(result.models, provider_id, provider_fields, entry)
    for model_id, override in (spec.get("modelOverrides") or {}).items():
        target = next(
            (m for m in result.models if m["provider"] == provider_id and m["id"] == model_id), None
        )
        if target is not None and isinstance(override, dict):
            _merge_fields(target, override)


def _merge_fields(model: Model, fields: dict[str, Any]) -> None:
    for key, value in fields.items():
        if isinstance(value, dict) and isinstance(model.get(key), dict):
            model[key] = {**model[key], **value}
        else:
            model[key] = copy.deepcopy(value)


def _upsert_model(
    models: list[Model], provider_id: str, provider_fields: dict[str, Any], entry: dict[str, Any]
) -> None:
    model: Model = copy.deepcopy(MODEL_DEFAULTS)
    model.update({"provider": provider_id, "name": entry["id"]})
    model.update(copy.deepcopy(provider_fields))
    model.update(copy.deepcopy(entry))
    model.setdefault("type", "chat")
    for index, current in enumerate(models):
        if current["provider"] == provider_id and current["id"] == entry["id"]:
            models[index] = model
            return
    models.append(model)


def is_supported(model: Model) -> bool:
    """Return whether piglet implements the model's API."""
    return model.get("api") in SUPPORTED_APIS


def supported_thinking_levels(model: Model) -> list[str]:
    """Return the thinking levels ``model`` accepts (Pi's ``getSupportedThinkingLevels``)."""
    if not model.get("reasoning"):
        return ["off"]
    level_map: dict[str, Any] = model.get("thinkingLevelMap") or {}
    levels = []
    for level in THINKING_LEVELS:
        if level in level_map and level_map[level] is None:
            continue
        if level in {"xhigh", "max"} and level not in level_map:
            continue
        levels.append(level)
    return levels


def clamp_thinking_level(model: Model, level: str) -> str:
    """Clamp ``level`` to the nearest supported level, preferring higher levels first."""
    available = supported_thinking_levels(model)
    if level in available:
        return level
    if level not in THINKING_LEVELS:
        return available[0] if available else "off"
    index = THINKING_LEVELS.index(level)
    for candidate in THINKING_LEVELS[index:]:
        if candidate in available:
            return candidate
    for candidate in reversed(THINKING_LEVELS[:index]):
        if candidate in available:
            return candidate
    return available[0] if available else "off"


def model_key(model: Model) -> str:
    """Return the ``provider/id`` key for ``model``."""
    return f"{model['provider']}/{model['id']}"


@dataclass(frozen=True)
class ScopedModel:
    """A model selected by a pattern, with an optional thinking-level suffix."""

    model: Model
    thinking_level: str | None = None


def split_thinking_suffix(text: str) -> tuple[str, str | None]:
    """Split ``pattern:level`` into ``(pattern, level)`` when ``level`` is a thinking level."""
    base, sep, suffix = text.rpartition(":")
    if sep and suffix in THINKING_LEVELS:
        return base, suffix
    return text, None


def _is_alias(model_id: str) -> bool:
    return model_id.endswith("-latest") or not _DATED_SUFFIX.search(model_id)


def _best_fuzzy(matches: list[Model]) -> Model | None:
    aliases = [m for m in matches if _is_alias(m["id"])]
    pool = aliases or matches
    return max(pool, key=lambda m: m["id"]) if pool else None


def resolve_reference(
    text: str, models: list[Model], usable: Callable[[str], bool], fuzzy: bool = True
) -> Model | None:
    """Resolve a model reference: exact ``provider/id``, exact id, then fuzzy substring.

    Ties between providers prefer one that ``usable`` reports as configured.

    Args:
        text: The reference (no thinking suffix).
        models: Candidate models.
        usable: Returns whether a provider has credentials.
        fuzzy: Whether substring matches are allowed.

    Returns:
        The matched model, or ``None``.
    """
    lower = text.strip().lower()
    if not lower:
        return None
    for model in models:
        if model_key(model).lower() == lower:
            return model
    exact = [m for m in models if m["id"].lower() == lower]
    if exact:
        return next((m for m in exact if usable(m["provider"])), exact[0])
    if not fuzzy:
        return None
    provider, _, rest = lower.partition("/")
    pool = [m for m in models if m["provider"].lower() == provider] if rest else models
    needle = rest if rest and pool else lower
    pool = pool or models
    matches = [
        m for m in pool if needle in m["id"].lower() or needle in str(m.get("name", "")).lower()
    ]
    usable_matches = [m for m in matches if usable(m["provider"])]
    return _best_fuzzy(usable_matches or matches)


def resolve_scope(
    patterns: Iterable[str], models: list[Model], usable: Callable[[str], bool]
) -> list[ScopedModel]:
    """Resolve ``enabledModels`` patterns (exact, ``provider/id``, glob or fuzzy, with ``:level``).

    Args:
        patterns: The patterns in order.
        models: Candidate models.
        usable: Returns whether a provider has credentials.

    Returns:
        The scoped models in pattern order, without duplicates.
    """
    scoped: list[ScopedModel] = []
    seen: set[str] = set()
    for raw in patterns:
        pattern, level = split_thinking_suffix(raw.strip())
        if any(ch in pattern for ch in "*?["):
            lowered = pattern.lower()
            matched = [
                m
                for m in models
                if fnmatch.fnmatchcase(model_key(m).lower(), lowered)
                or fnmatch.fnmatchcase(m["id"].lower(), lowered)
            ]
        else:
            found = resolve_reference(pattern, models, usable)
            matched = [found] if found else []
        for model in matched:
            if model_key(model) not in seen:
                seen.add(model_key(model))
                scoped.append(ScopedModel(model, level))
    return scoped


def find_initial_model(
    models: list[Model],
    usable: Callable[[str], bool],
    settings: dict[str, Any],
    scoped: list[ScopedModel],
) -> Model | None:
    """Pick the startup model the way Pi's ``findInitialModel`` does.

    Order: the first scoped model, then ``defaultProvider``/``defaultModel`` if that provider has
    auth, then the first available provider default, then any available model.

    Args:
        models: All models.
        usable: Returns whether a provider has credentials.
        settings: Effective settings.
        scoped: Resolved ``enabledModels``.

    Returns:
        The chosen model, or ``None`` when no provider is configured.
    """
    if scoped:
        return scoped[0].model
    available = [m for m in models if usable(m["provider"]) and is_supported(m)]
    default_provider = settings.get("defaultProvider")
    default_model = settings.get("defaultModel")
    if default_provider and default_model and usable(default_provider):
        for model in models:
            if model["provider"] == default_provider and model["id"] == default_model:
                return model
    for model in available:
        if DEFAULT_MODEL_PER_PROVIDER.get(model["provider"]) == model["id"]:
            return model
    return available[0] if available else None
